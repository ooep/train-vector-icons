# 每个公司的"通用車両"组（取该公司最有代表性的现役通勤组）
def co_general(co_names, jp_keywords):
    """在指定公司里找通用通勤组"""
    cands = []
    for g in allg:
        if g["co"] not in co_names: continue
        for kw in jp_keywords:
            if kw.lower() in g["jp"].lower() or kw.lower() in g["en"].lower():
                cands.append(g); break
    # 优先现役
    cur = [g for g in cands if not g["jp"].startswith("*") and "ラッピング" not in g["jp"] and "イベント" not in g["jp"]]
    return cur[0] if cur else (cands[0] if cands else None)

